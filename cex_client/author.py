def _stamp_intent(ws: Workspace, root: Path, batch: Path, case_root: Path, aid: str,
                  receipt: dict[str, Any], case: dict[str, Any] | None,
                  ctx: dict[str, Any] | None = None,
                  outcome: dict[str, Any] | None = None) -> tuple[dict[str, Any],
                                                                  dict[str, Any] | None]:
    """nodes.py `_stamp_intent`：每案 intent.json（author_claims 是断言兑现 Author 期望的出处），
    落在本批的每案目录 case_root/<autoid>/。绑定规范（requirement=required）的案在这里顺带
    把密封结论打包成一致性工件（`cex_client.consistency`）；打包成功才把 intent 的绑定章盖成
    complete，缺证据的案保持 pending 并落 brief，等 `cex_consistency_record` 补包。
    传 outcome 时不再推导（record 工具用同一份结论重写 intent）."""
    from cex_core.engine.case_compiler._sealed_io import read_regular_nofollow
    from cex_core.engine.case_compiler.contract_entry import (
        normalize_contract,
        write_intent_json_atomic,
        write_json_atomic,
    )
    from cex_core.engine.case_compiler.domain_grammar import forbidden_mechanism_intents
    from cex_core.engine.ist_core.compile_engine.consistency_requirement import (
        REQUIRED,
        resolve_consistency_requirement,
    )

    case_dir = case_root / safe_component(aid, "autoid")
    marker = case_dir / "intent_stamp_status.json"
    case_dir.mkdir(parents=True, exist_ok=True)
    write_json_atomic(marker, {"schema": _INTENT_STAMP_SCHEMA, "autoid": aid, "status": "pending"})
    if not isinstance(case, dict):
        raise ClientError(f"case {aid} is missing from the mindmap")
    payload: dict[str, Any] = {
        "autoid": aid, "title": str(case.get("title") or ""),
        "step_intents": case.get("step_intents") or [], "group_path": case.get("group_path") or [],
        "source": "manifest", "stamped_by": "engine.author",
        "consistency_requirement": "required", "consistency_binding_status": "pending",
        "consistency_contract_path": None, "consistency_contract_sha256": None,
        "consistency_receipt_sha256": None,
        "governing_spec_status": str(receipt.get("governing_spec_status") or "unknown"),
    }
    if receipt.get("governing_spec_status") == "bound":
        payload["governing_spec"] = receipt.get("governing_spec")
        payload["governing_spec_identity"] = {
            key: receipt.get(f"governing_spec_{field}") for key, field in (
                ("name", "name"), ("sha256", "sha256"), ("size", "size"),
                ("generation_id", "generation_id"), ("manifest_sha256", "manifest_sha256"))}
        payload["governing_spec_identity"]["name"] = receipt.get("governing_spec")
    contract_path = batch / "contracts" / f"{aid}.json"
    expected = str((receipt.get("contract_sha256_by_autoid") or {}).get(aid) or "")
    raw = read_regular_nofollow(
        contract_path, trusted_root=ws.outputs_dir, error_type=ClientError,
        invalid_message="machine contract path is invalid",
        directory_message="machine contract directory is unavailable",
        open_message="machine contract is unavailable",
        bounds_message="machine contract exceeds its sealed size boundary",
        changed_message="machine contract changed while being read",
        max_bytes=16 * 1024 * 1024, min_bytes=1)
    if _sha256_bytes(raw) != expected:
        raise ClientError(f"typed expectation contract identity drift for {aid}")
    contract = json.loads(raw.decode("utf-8"))
    payload["typed_expectation_contract_sha256"] = expected
    payload["typed_expectation_contract_path"] = contract_path.relative_to(ws.root).as_posix()
    status = str(contract.get("typed_assertion_status") or "ready")
    if status not in ("ready", "pending"):
        raise ClientError("typed expectation contract status is invalid")
    payload["typed_expectation_status"] = status
    typed, claims, defect_claims = {}, {}, {}
    for item in normalize_contract(contract, contract_path.name).get("expectations") or []:
        assertion = item.get("assertion") if isinstance(item, dict) else None
        claim = item.get("author_claim") if isinstance(item, dict) else None
        defect_claim = item.get("defect_spec_claim") if isinstance(item, dict) else None
        if isinstance(assertion, dict):
            typed[str(assertion.get("expectation_id") or "")] = assertion
        elif isinstance(claim, dict):
            claims[str(claim.get("expectation_id") or "")] = claim
        elif isinstance(defect_claim, dict):
            defect_claims[str(defect_claim.get("expectation_id") or "")] = defect_claim
        else:
            raise ClientError("typed expectation entry is absent")
    payload.update({"typed_expectations": typed, "author_claims": claims,
                    "defect_spec_claims": defect_claims})
    proof = resolve_consistency_requirement(outputs_root=ws.outputs_dir, project_root=root,
                                            batch_name=batch.name, autoid=aid, facts=[receipt])
    payload["governing_spec_status"] = proof["governing_spec_status"]
    payload["consistency_requirement"] = proof["requirement"]
    payload["consistency_binding_status"] = proof["binding_status"]
    if outcome is None and ctx is not None and proof["requirement"] == REQUIRED:
        try:
            outcome = consistency.derive_from_conclusion(
                aid=aid, card=contract, card_sha256=expected,
                mm_case=ctx["mm_cases"].get(aid) or {}, mindmap_text=ctx["text"],
                spec_name=ctx["spec_name"], spec_text=ctx["spec_text"],
                defect_receipt=ctx["defect_receipt"], case_root=case_root)
        except ClientError:
            raise  # 数据根/盘级故障是批级问题，如实上抛
        except (ValueError, OSError, RecursionError) as exc:
            # 引擎的判据不该在单案上炸整批：按 pending_record 记码，出路照旧点名
            outcome = {"status": consistency.STATUS_PENDING,
                       "code": f"consistency_record_invalid: {type(exc).__name__}",
                       "detail": str(exc)[:400], "fixed_verdict": None}
    if outcome is not None and outcome.get("status") == consistency.STATUS_SEALED:
        payload.update(consistency.intent_binding(
            outcome, overlay=consistency.overlay_path(case_root, aid), project_root=ws.root))
    haystack = " ".join([payload["title"]] + [
        f"{si.get('desc') or ''} {si.get('expected') or ''}"
        for si in payload["step_intents"] if isinstance(si, dict)]).lower()
    hits = [{"family": family, "matched": pattern}
            for family, patterns in forbidden_mechanism_intents()
            for pattern in patterns if re.search(pattern, haystack)]
    if hits:
        payload["forbidden_mechanism"] = hits[:3]
    write_intent_json_atomic(case_dir / "intent.json", payload)
    write_json_atomic(marker, {"schema": _INTENT_STAMP_SCHEMA, "autoid": aid, "status": "complete"})
    return proof, outcome


