def _step_source(prov: dict[str, Any]) -> dict[str, str]:
    source = prov.get("source") if isinstance(prov.get("source"), dict) else {}
    kind = str(source.get("kind") or "").strip()
    ref = str(source.get("locator") or source.get("ref") or "").strip()
    return {"kind": kind, "ref": ref} if kind and ref else {}


def expand_case(path: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """封存的机械用例 → 工作簿步骤（与引擎 emit 同一展开：块 → 步骤 → 派生断言降级）。"""
    from cex_core.engine.case_compiler.blocks import (
        expand_blocks,
        lower_derived_assertions,
    )
    from cex_core.engine.case_compiler.mechanical_case import load_mechanical_case

    case, _sha = load_mechanical_case(path)
    body = case.model_dump(mode="python", by_alias=True)
    steps, prov, error = expand_blocks(list(body["blocks"]))
    if error or steps is None:
        raise ClientError(f"{path}: blocks do not expand: {error}")
    steps, prov, error = lower_derived_assertions(steps, prov)
    if error or steps is None:
        raise ClientError(f"{path}: derived assertions do not lower: {error}")
    out = []
    init = "\n".join(str(c) for c in body.get("init_commands") or [] if str(c).strip())
    if init:
        # 引擎 emit（merge_case_producer_rules）同样把本案前置放成第一步
        out.append({"E": "APV_0", "F": "cmds_config", "G": init, "desc": "case 自包含前置配置"})
    for step, item in zip(steps, prov or [{}] * len(steps), strict=False):
        row = {"E": step.get("E"), "F": step.get("F"), "G": step.get("G", ""),
               "desc": step.get("desc") or ""}
        for key in ("H", "I"):
            if step.get(key) not in (None, ""):
                row[key] = step[key]
        if str(step.get("E") or "").strip() == "check_point":
            source = _step_source(item or {})
            if source:
                row["source"] = source
        out.append(row)
    return body, out


def emit(ws: Workspace, out_name: str) -> dict[str, Any]:
    state = _load_state(ws, out_name)
    engine_env.prepare(ws)
    receipt = state.get("receipt") or {}
    sealed = state.get("sealed") or {}
    missing = [aid for aid in receipt.get("written_autoids") or [] if aid not in sealed]
    cases = []
    for aid in receipt.get("written_autoids") or []:
        if aid not in sealed:
            continue
        body, steps = expand_case(Path(sealed[aid]["artifact"]))
        if (body.get("binding") or {}).get("contract_sha256") != \
                (receipt.get("contract_sha256_by_autoid") or {}).get(aid):
            missing.append(aid)  # 封存时的契约卡已不是现在这张：要按新卡重新提交
            continue
        description = body.get("description") or {}
        cases.append({"autoid": aid, "priority": "P1",
                      "description": str(description.get("intent_verbatim") or ""),
                      "steps": steps})
    if not cases:
        raise ClientError("no sealed mechanical case to emit; submit cases with "
                          "cex_author_submit_case first")
    batch = ws.outputs_dir / state["out_name"]
    doc = {"batch": state["out_name"], "cases": cases, "_generated": _CASES_SCHEMA_NOTE}
    cases_path = batch / "cases.json"
    cases_path.write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    from .skill_scripts import compile_workbook, verify_workbook

    result = compile_workbook(cases_path, ws.outputs_dir)
    verify = verify_workbook(Path(result["path"]))
    return {"ok": bool(result.get("ok")) and verify.get("fail") == 0,
            "xlsx": result.get("path"), "cases_json": str(cases_path),
            "emitted_autoids": [c["autoid"] for c in cases], "not_sealed_autoids": missing,
            "verify": {"pass": verify.get("pass"), "fail": verify.get("fail"),
                       "failures": verify.get("failures")}}


