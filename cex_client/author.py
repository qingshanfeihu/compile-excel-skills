"""编写阶段在客户端的编排：已密封的机械脑图 → 契约卡 → 机械用例 → 出件用例。

InfoTest 里这一段由编译引擎做：recompose 节点的投影段把机械脑图投成每案一张契约卡
（期望原文 + 引擎裁定的判据类型 + 允许的断言块与算子），author 节点给每案盖 intent 章、派
compile-worker 写机械用例（块语言）并经 submit_mechanical_case 的提交规则闸封存，emit 把
封存的用例展开成工作簿。客户端没有引擎，这里把那层薄胶水按原顺序移植过来；判据（契约投影、
判据台账与裁定复核、提交规则闸、块展开、派生断言收据）一律调 cex_core.engine 抽取来的同一批
函数，不重写：

- prepare：nodes.py `recompose` 的投影段（fill_mechanical_fields → 结构/逐字隔离 →
  project_machine_mindmap → 判据待裁定就停下 → 预检 → 原子发布 contracts/ 与披露旁车 →
  recompose_done 回执）+ `_stamp_intent`（每案 intent.json，写 author_claims）。
- criterion_record：引擎把待裁定的判据形状交给 criterion-adjudicator fork；客户端把同一份
  单形状 brief 交给当前模型，回执经 parse_engine_adjudication_result 机械复核、
  persist_engine_adjudications 入台账（同时记进工作区，换数据包后接着用），全部裁完重投影。
- submit_case：submit_mechanical_case 的判定链——冻结契约、盖引擎绑定、SSL_CERT_LOAD 标准库
  降级、提交规则闸（run_mechanical_case_gate）、豁免账、铸封落盘。
- emit：expand_blocks + lower_derived_assertions 展开封存的机械用例（与引擎 emit 同一展开），
  出 cases.json（断言步带引擎给的出处），交给 compile_excel 出件。

与引擎的差别（都只在这层胶水里）：
- 不移植 worker 会话：修补轮省略 expectation_binding / escape_hatches 的续传、重复拒收计数、
  会话准入与事实账都没有；每次提交都要带完整的八段主体，按整份从头判。
- 规格一致性（case 与管辖规格书的一致性裁决，scenario 1）按机械打包移植：裁决本身在重组
  阶段按 [R11] 做出并密封到契约卡，编写期由 `cex_client.consistency` 调引擎同一批函数把它
  打成判据材料与 consistency_contract.json 覆盖层（引文与 premises 逐字节按密封出处复核）；
  卡上证据不全的案子点名进 `cex_consistency_record` 补包（卡上有结论时 verdict 由结论映射
  强制，模型改不动）；案内互斥按引擎判据案级放弃。recompose 时 spec='none' 走不适用。
  与引擎的差别只在工件位置：没有服务端 dispatch 台账，材料与回执记在本批编写状态里，
  覆盖层落在 compile_outputs/<批>/cases/<autoid>/consistency_contract.json。
- answerer 为 undetermined 的观察块不经引擎写用户裁决账，直接如实返回待用户裁决，不封存。
- 客户端的产物根是工作区 compile_outputs/（引擎是 workspace/outputs/）。每案目录（intent.json、
  封存的 mechanical_case.json）放在本批目录下 compile_outputs/<批>/cases/<autoid>/，两个批次含
  同一 autoid 也互不覆盖；引擎读每案目录的地方（提交规则闸的出处核对）把 outputs_root 指到这里。
  旧版放在 compile_outputs/<autoid>/ 的批次照读：下一次提交时按本批回执把 intent 重盖到新位置，
  出件时把核过哈希的封存用例搬进本批目录；intent.json 里的契约路径相对工作区根记；
- 出件逐案核封存时记下的 mechanical_case_sha256：文件被换过（别的批、手工改）就不出这一案并点名；
  有未封存或被换过的案时 ok=false；
- 状态"读—改—写"都在工作区锁里做（同时提交几案不会丢封存记录），状态里的路径相对工作区根记；
  整批钉在重组开始时的引擎数据根上（engine_env.pinned_root）。
"""

