def _violation(code: str, locus: str, detail: str, gate: str = "dispatch_binding") -> dict[str, str]:
    return {"gate": gate, "code": code, "locus": locus, "detail": detail}


def submit_case(ws: Workspace, out_name: str, mechanical_case: Any) -> dict[str, Any]:
    state = _load_state(ws, out_name)
    if state.get("phase") != "published":
        raise ClientError("contracts are not published yet; finish cex_author_prepare "
                          "(and any cex_criterion_record) first")
    _require_current_seal(ws, state)
    root, _info = engine_env.prepare(ws, pinned=state.get("data_root"))
    if isinstance(mechanical_case, str):
        try:
            mechanical_case = json.loads(mechanical_case)
        except ValueError as exc:
            return _reject("", [_violation("payload_invalid_json", "mechanical_case", str(exc),
                                           gate="mechanical_case_body")])
    if not isinstance(mechanical_case, dict):
        return _reject("", [_violation("not_an_object", "mechanical_case",
                                       "mechanical_case must be one JSON object",
                                       gate="mechanical_case_body")])
    body = dict(mechanical_case)
    aid = str(body.get("autoid") or "")
    receipt = state["receipt"]
    if aid not in (receipt.get("written_autoids") or []):
        return _reject(aid, [_violation("autoid_not_dispatched", "autoid",
                                        f"{aid!r} is not a contracted case of {out_name}; "
                                        f"contracted: {receipt.get('written_autoids')}")])
    if "seal" in body:
        return _reject(aid, [_violation("self_reported_seal", "seal",
                                        "do not include seal; the engine mints it after the gates pass",
                                        gate="mechanical_case_body")])
    from cex_core.engine.ist_core.compile_engine.consistency_requirement import (
        NOT_APPLICABLE,
        REQUIRED,
        ConsistencyRequirementError,
        resolve_consistency_requirement,
    )

    batch = ws.outputs_dir / state["out_name"]
    was_legacy = not state.get("cases_root")
    text = (batch / "mindmap_source.json").read_bytes().decode("utf-8").lstrip(_STRIP)
    case_root = _ensure_cases_root(ws, state, root, batch, text)
    if was_legacy:
        # 迁移把每案的一致性与 intent 重盖进状态：接着按新状态判
        state = _load_state(ws, out_name)
        receipt = state["receipt"]
    case_state = (state.get("cases") or {}).get(aid) or {}
    requirement = case_state.get("consistency_requirement")
    cons = case_state.get("consistency") or {}
    if requirement not in (NOT_APPLICABLE, REQUIRED):
        return _reject(aid, [_violation(
            "consistency_requirement_drift", "consistency_requirement",
            "the authoring state does not carry this case's consistency requirement; call "
            "cex_author_prepare again")])
    if requirement == REQUIRED:
        # 引擎提交链的顺序：案级放弃先按密封结论定案（recompose_abandon_actionable），
        # 再查裁决工件；这里的台账是本批编写状态，工件在盘上提交期再对合一次。
        if not cons:
            return _reject(aid, [_violation(
                "consistency_verdict_missing", "consistency_verdict",
                "this batch was authored before the consistency stage landed: call "
                "cex_author_prepare to derive this case's verdict package before submitting")])
        if cons.get("status") == consistency.STATUS_ABANDONED:
            return _reject(aid, [_violation(
                "case_abandoned_by_consistency", "consistency_verdict",
                str(cons.get("detail") or "abandoned by the sealed consistency conclusion")
                + "; resubmitting changes nothing here")])
        if cons.get("status") != consistency.STATUS_SEALED:
            return _reject(aid, [_violation(
                "consistency_verdict_missing", "consistency_verdict",
                f"this case is bound to a governing spec and its verdict package is "
                f"incomplete ({cons.get('code') or 'unknown'}): {cons.get('detail') or ''} "
                f"Read the brief ({cons.get('brief_path') or 'missing'}) and record it with "
                "cex_consistency_record before submitting")])
    contract_raw = (batch / "contracts" / f"{aid}.json").read_bytes()
    contract_sha = _sha256_bytes(contract_raw)
    if contract_sha != receipt["contract_sha256_by_autoid"].get(aid):
        return _reject(aid, [_violation("frozen_contract_drift", "contracts",
                                        "the contract card changed after it was published; call "
                                        "cex_author_prepare again")])
    contract = json.loads(contract_raw.decode("utf-8"))
    overlay: dict[str, Any] | None = None
    overlay_sha = ""
    if requirement == REQUIRED:
        # 提交期对合：旁车按回执重闭封，材料↔覆盖层↔冻结卡↔密封机械案四方一致（引擎在
        # dispatch 台账上做的同一件事，客户端的台账是编写状态）。
        try:
            proof = resolve_consistency_requirement(outputs_root=ws.outputs_dir, project_root=root,
                                                    batch_name=state["out_name"], autoid=aid,
                                                    facts=[receipt])
        except ConsistencyRequirementError as exc:
            return _reject(aid, [_violation(exc.code, "consistency_requirement", exc.detail)])
        if proof["requirement"] != REQUIRED:
            return _reject(aid, [_violation(
                "consistency_requirement_drift", "consistency_requirement",
                "the sealed evidence says this case needs no verdict package but the authoring "
                "state carries one; call cex_author_prepare again")])
        overlay, overlay_sha, error = consistency.load_and_verify(
            aid=aid, record=cons, card=contract, card_sha256=contract_sha,
            mm_case=_sealed_machine_case(batch, aid), case_root=case_root)
        if error:
            return _reject(aid, [_violation("consistency_contract_invalid",
                                            "consistency_contract.json", error)])
    from cex_core.engine.case_compiler.mechanical_case import (
        mint_and_land_mechanical_case,
    )
    from cex_core.engine.case_compiler.mechanical_case_gate import (
        AUDIENCE_WORKER,
        gate_report_digest,
        run_mechanical_case_gate,
    )
    from cex_core.engine.case_compiler.vendor_stdlib import configured_device_os_build
    from cex_core.engine.engine_managed_outputs import MECHANICAL_CASE_SIDECAR_NAME
    from cex_core.engine.ist_core.tools.device.mechanical_case_submit_tool import (
        _canonicalize_submission_blocks,
        _stamp_engine_binding,
        unique_exempt_blocks_submit,
    )

    capability = state.get("capability") or {}
    session = SimpleNamespace(capability_generation_id=capability.get("generation_id") or "",
                              capability_projection_sha256=capability.get("projection_sha256") or "",
                              authored_round=1, source_manifest_ref="", source_manifest_sha256="")
    if body.get("binding") is None:
        body["binding"] = {}
    if body.get("escape_hatches") is None:
        # 引擎的提交工具同样把省略的 escape_hatches 当空数组（没有 STEP 块时本来就是空的）
        body["escape_hatches"] = []
    body, violations = _stamp_engine_binding(body, contract=contract, contract_sha256=contract_sha,
                                            consistency_contract_sha256=overlay_sha or None,
                                            session=session, project_root=root)
    if violations:
        return _reject(aid, violations)
    body, error = _canonicalize_submission_blocks(body)
    if body is None:
        return _reject(aid, [_violation("ssl_cert_load_invalid", "blocks", error,
                                        gate="mechanical_case_body")])
    undetermined = [block.get("answerer", {}).get("note") for block in body.get("blocks") or []
                    if isinstance(block, dict) and isinstance(block.get("answerer"), dict)
                    and block["answerer"].get("kind") == "undetermined"]
    if undetermined:
        return {"ok": False, "status": "needs_user_decision", "autoid": aid,
                "claims": undetermined,
                "detail": "an observation names no answerer; nothing is sealed. Ask the user who "
                          "answers it, or rewrite the block with a determined answerer."}
    _require_identity_table(body)
    slice_, slice_sha = source_case_slice(_manifest_cases(text)[aid], aid)
    try:
        # 引擎按 outputs_root/<autoid>/intent.json 核出处：指到本批自己的每案目录
        ok, report = run_mechanical_case_gate(
            body, contract, contract_sha256=contract_sha, device_build=configured_device_os_build(),
            outputs_root=case_root, consistency_contract=overlay,
            consistency_contract_sha256=overlay_sha,
            consistency_required=requirement == REQUIRED,
            source_case_slice=slice_, source_case_slice_sha256=slice_sha)
    except (TypeError, ValueError, RecursionError) as exc:
        return _reject(aid, [_violation("gate_uncomputable", "mechanical_case",
                                        f"the mechanical case could not be gated: {type(exc).__name__}: {exc}",
                                        gate="mechanical_case_body")])
    advisories = [{k: str(item.get(k) or "") for k in ("gate", "code", "locus", "detail")}
                  for item in report.get("advisories") or []]
    if not ok:
        found = []
        for item in report.get("hard_rejects") or []:
            if item.get("audience") != AUDIENCE_WORKER:
                continue
            finding = {k: str(item.get(k) or "") for k in ("gate", "code", "locus", "detail")}
            if isinstance(item.get("expectation_ids"), list):
                finding["expectation_ids"] = [str(v) for v in item["expectation_ids"] if str(v)]
            found.append(finding)
        others = [item for item in report.get("hard_rejects") or []
                  if item.get("audience") != AUDIENCE_WORKER]
        if others and not found:
            found = [{k: str(item.get(k) or "") for k in ("gate", "code", "locus", "detail")}
                     for item in others]
        return _reject(aid, found, advisories)
    exempt = unique_exempt_blocks_submit(body)
    if exempt is not None:
        return _reject(aid, [exempt], advisories)
    measurements = report["measurements"]
    artifact = case_root / aid / MECHANICAL_CASE_SIDECAR_NAME
    republished: list[bool] = []
    with state_lock(ws, "author-case", f"{state['out_name']}/{aid}"):
        # 同一案同时提交两次：落盘与记账在同一把锁里，记下的哈希总是文件里那一份
        minted = mint_and_land_mechanical_case(
            dict(body), artifact,
            capabilities_used=list(measurements["capabilities_used"]),
            expanded_step_count=int(measurements["expanded_step_count"]),
            check_point_count=int(measurements["check_point_count"]),
            gate_report_sha256=gate_report_digest(report))
        if minted.document is None:
            return _reject(aid, [_violation(minted.code, "case", minted.detail, gate="seal")],
                           advisories)
        seal = minted.document["seal"]

        def record(current: dict[str, Any]) -> None:
            contracts = (current.get("receipt") or {}).get("contract_sha256_by_autoid") or {}
            if current.get("phase") != "published" or contracts.get(aid) != contract_sha:
                republished.append(True)
                return
            current.setdefault("sealed", {})[aid] = {
                "artifact": to_state_path(ws, artifact),
                "mechanical_case_sha256": seal["mechanical_case_sha256"],
                "contract_sha256": contract_sha}

        current = _update_state(ws, state["out_name"], record)
    if republished:
        return _reject(aid, [_violation(
            "contracts_republished", "contracts",
            "cex_author_prepare re-published the contract cards while this case was being "
            "checked; nothing was recorded. Read the new card and submit the case again")],
            advisories)
    written = (current.get("receipt") or {}).get("written_autoids") or []
    remaining = [a for a in written if a not in (current.get("sealed") or {})
                 and (((current.get("cases") or {}).get(a) or {}).get("consistency") or {})
                 .get("status") != consistency.STATUS_ABANDONED]
    return {"ok": True, "status": "sealed", "autoid": aid, "artifact": str(artifact),
            "mechanical_case_sha256": seal["mechanical_case_sha256"],
            "expanded_step_count": measurements["expanded_step_count"],
            "check_point_count": measurements["check_point_count"],
            "advisories": advisories, "remaining_autoids": remaining}


def _precedent_blocks(blocks: Any) -> list[int] | None:
    """引用 precedent（框架里已验证的用例包）的块下标；按引擎自己的展开判定（块级与断言级 ref
    都算）。展开不了返回 None——闸会自己报展开错误。"""
    from cex_core.engine.case_compiler.blocks import expand_blocks

    blocks = list(blocks or []) if isinstance(blocks, list) else []
    try:
        _steps, prov, error = expand_blocks(blocks)
    except (TypeError, ValueError, RecursionError):
        return None
    if error or not prov:
        return None
    if not any(isinstance(item, dict) and isinstance(item.get("source"), dict)
               and item["source"].get("kind") == "precedent" for item in prov):
        return []

    def cites(ref: Any) -> bool:
        return str(ref or "").partition(":")[0].strip() == "precedent"

    return [i for i, block in enumerate(blocks) if isinstance(block, dict) and (
        cites(block.get("ref")) or any(isinstance(a, dict) and cites(a.get("ref"))
                                       for a in block.get("asserts") or []))] or [-1]


def _identity_table_missing() -> str:
    """引擎外置的身份表（拒用用例包的真实案号）不可用时给出原因，可用时给空串。"""
    from cex_core.engine._root import IdentityListUnavailable
    from cex_core.engine.case_compiler.package_advisories import DENIED_668_AUTOIDS

    try:
        len(DENIED_668_AUTOIDS)
    except IdentityListUnavailable as exc:
        return str(exc)
    return ""


def _require_identity_table(body: dict[str, Any]) -> None:
    """提交规则闸要拿引擎的拒用包身份表核每个 precedent 出处；发行版不带这张表（没设
    CEX_ENGINE_IDENTITIES）时闸只会报一个看不出原因的 E_PACKAGE_INDEX_UNAVAILABLE。这里先说清楚：
    缺的是什么、没有它这个工具收不了 precedent 出处、可以怎么改。"""
    blocks = _precedent_blocks(body.get("blocks"))
    if not blocks:
        return
    missing = _identity_table_missing()
    if not missing:
        return
    where = (f"block(s) {[i for i in blocks if i >= 0]}" if blocks != [-1]
             else "an expanded step")
    raise ClientError(
        f"{where} cite a precedent source, and cex_author_submit_case cannot accept one without the "
        "engine's identity table (the denied-package case numbers every precedent is checked "
        f"against), which this installation does not have: {missing}. Cite the manual, a footprint "
        "or the stamped intent instead, or ask the maintainer to install the identity table")


def _ensure_cases_root(ws: Workspace, state: dict[str, Any], root: Path, batch: Path,
                       text: str) -> Path:
    """本批的每案目录。旧版状态的 intent.json 在 compile_outputs/<autoid>/（同 autoid 的别的批会
    覆盖它）：按本批回执把每案重盖到本批目录下再接着写（迁移只发生在要写的时候）。重盖同样
    打包一致性工件，并把结果记回状态里——不然迁移完的 bound 批每案提交都少一份台账。"""
    from cex_core.engine.ist_core.compile_engine.consistency_requirement import REQUIRED

    case_root = cases_root(ws, state["out_name"])
    if state.get("cases_root"):
        return case_root
    with state_lock(ws, "author-migrate", state["out_name"]):
        # 同时提交的几案只迁移一次：锁内再看一眼状态
        current = read_private_json(_state_path(ws, state["out_name"])) or {}
        if not current.get("cases_root"):
            receipt = state.get("receipt") or {}
            manifest_cases = _manifest_cases(text)
            written = receipt.get("written_autoids") or []
            old_cases = current.get("cases") or {}
            needs_ctx = any((old_cases.get(a) or {}).get("consistency_requirement") == REQUIRED
                            for a in written)
            ctx = _consistency_ctx(root, batch, text) if needs_ctx else None
            restamped: dict[str, tuple[dict[str, Any], dict[str, Any] | None]] = {}
            for aid in written:
                proof, outcome = _stamp_intent(ws, root, batch, case_root, aid, receipt,
                                               manifest_cases.get(aid), ctx)
                record = (_consistency_record(ws, batch, case_root, aid, state["out_name"],
                                              outcome, ctx) if outcome is not None else None)
                restamped[aid] = (proof, record)

            def merged(cur: dict[str, Any]) -> None:
                cur["cases_root"] = to_state_path(ws, case_root)
                for aid, (proof, record) in restamped.items():
                    entry = cur.setdefault("cases", {}).setdefault(aid, {})
                    entry["consistency_requirement"] = proof["requirement"]
                    if record is None:
                        entry.pop("consistency", None)
                    else:
                        entry["consistency"] = record

            _update_state(ws, state["out_name"], merged)
    state["cases_root"] = to_state_path(ws, case_root)
    return case_root


