# ── 状态 ────────────────────────────────────────────────────────────────


def _state_path(ws: Workspace, out_name: str) -> Path:
    return ws.state_dir / "author" / f"{safe_component(out_name, 'batch name')}.json"


def _load_state(ws: Workspace, out_name: str) -> dict[str, Any]:
    state = read_private_json(_state_path(ws, out_name))
    if not state or state.get("schema") != STATE_SCHEMA:
        raise ClientError(f"no authoring dispatch for {out_name!r}; call cex_author_prepare")
    return state


def _save_state(ws: Workspace, state: dict[str, Any]) -> None:
    write_private_json(_state_path(ws, state["out_name"]), {**state, "schema": STATE_SCHEMA})


def _sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _canonical_sha256(value: Any) -> str:
    return _sha256_bytes(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(",", ":")).encode("utf-8"))


# ── 输入：已密封的机械脑图与它的来源状态 ──────────────────────────────────


def _sealed_batch(ws: Workspace, out_name: str) -> tuple[dict[str, Any], Path]:
    from . import recompose

    rstate = recompose._load_state(ws, out_name)
    from cex_core.engine.ist_core.tools.device.recompose_submission import (
        verify_machine_mindmap_submission_commit,
    )

    try:
        verify_machine_mindmap_submission_commit(ws.outputs_dir, rstate["out_name"],
                                                 rstate["dispatch_id"],
                                                 expected_binding=rstate["binding"])
    except Exception as exc:  # noqa: BLE001 — 引擎的密封核对：任何不过都等于没密封
        raise ClientError(f"the machine mindmap of {out_name!r} is not sealed "
                          f"({type(exc).__name__}: {exc}); call cex_recompose_seal first") from None
    return rstate, ws.outputs_dir / rstate["out_name"]


def _status(batch: Path, name: str) -> tuple[dict[str, Any], bytes]:
    raw = (batch / name).read_bytes()
    return json.loads(raw.decode("utf-8")), raw


def _spec_text(root: Path, spec_status: dict[str, Any]) -> str | None:
    if spec_status.get("status") != "bound":
        return None
    path = (root / "knowledge" / "data" / "spec" / "generations"
            / safe_component(spec_status.get("generation_id"), "spec generation")
            / "docs" / safe_component(spec_status.get("name"), "spec name"))
    raw = path.read_bytes()
    if _sha256_bytes(raw) != spec_status.get("sha256"):
        raise ClientError("the bound governing spec changed after recompose; call "
                          "cex_recompose_prepare again")
    return raw.decode("utf-8", errors="replace")


def _manifest_cases(text: str) -> dict[str, dict[str, Any]]:
    """InfoTest compile_prep 从脑图抽出的每案切片（标题、step_intents、分组路径）。"""
    from cex_core.engine.ist_core.tools.device import compile_prep

    roots = json.loads(text)
    cases: dict[str, dict[str, Any]] = {}
    for root in roots if isinstance(roots, list) else [roots]:
        if isinstance(root, dict):
            for case in compile_prep._extract_cases(root):
                cases[str(case["autoid"])] = case
    return cases


def source_case_slice(case: dict[str, Any], autoid: str) -> tuple[dict[str, Any], str]:
    """worker_device_context.canonical_source_case_slice 与它的摘要（同一规范化）。"""
    from cex_core.engine.ist_core.worker_device_context import (
        canonical_source_case_slice,
        canonical_source_case_slice_sha256,
    )

    canonical = canonical_source_case_slice(case, autoid=autoid)
    return canonical, canonical_source_case_slice_sha256(canonical, autoid=autoid)


def _versions(info: dict[str, Any]) -> tuple[str, str, str]:
    """(完整版本, 判据版本族 如 10.5, 手册版本 如 10.5.0)。"""
    from cex_core.engine.case_compiler.criterion_author_rules import (
        resolve_compile_manual_version,
    )
    from cex_core.engine.case_compiler.vendor_stdlib import (
        _inventory_version_from_device_build,
    )

    full = str(info.get("device_os_build") or "")
    return (full, _inventory_version_from_device_build(full),
            resolve_compile_manual_version(full_version=full))


# ── 投影（nodes.py recompose 的投影段） ──────────────────────────────────


def _project(root: Path, batch: Path, rstate: dict[str, Any], info: dict[str, Any],
             *, rule_records: dict | None) -> dict[str, Any]:
    from cex_core.engine.case_compiler.mindmap_contract_projector import (
        fill_mechanical_fields,
        load_machine_mindmap,
        project_machine_mindmap,
        verbatim_failures,
    )
    from cex_core.engine.case_compiler.step_structure import (
        object_kind_closed_set,
        sealed_structure_failures,
        strip_engine_slots,
    )

    spec_status, _ = _status(batch, "governing_spec_status.json")
    defect, _ = _status(batch, "defect_spec_status.json")
    source_raw = (batch / "mindmap_source.json").read_bytes()
    text = source_raw.decode("utf-8").lstrip(_STRIP)
    spec_text = _spec_text(root, spec_status)
    spec_name = spec_status.get("name") if spec_status.get("status") == "bound" else None
    defect_receipt = defect.get("receipt") if isinstance(defect.get("receipt"), dict) else None
    mm_path = batch / "machine_mindmap.json"
    mm_data, mm_sha = load_machine_mindmap(mm_path)
    fill_mechanical_fields(mm_data, text)
    kinds = object_kind_closed_set()
    structure_bad: dict[str, list[str]] = {}
    for case in mm_data.get("cases") or []:
        if not isinstance(case, dict):
            continue
        strip_engine_slots(case)
        codes = sealed_structure_failures(case, object_kinds=kinds)
        if codes:
            structure_bad[str(case.get("autoid") or "")] = codes
    bad = verbatim_failures(
        mm_data, text, spec_text, governing_spec=spec_name,
        governing_spec_status=str(spec_status["status"]), defect_spec_receipt=defect_receipt,
        defect_spec_status=str(defect["status"]),
        defect_spec_receipt_sha256=str(defect.get("receipt_sha256") or "") or None)
    _full, family, manual = _versions(info)
    staging = batch / f".author-projection-{uuid.uuid4().hex}"
    staging.mkdir()
    shutil.copyfile(mm_path, staging / "machine_mindmap.json")
    summary = project_machine_mindmap(
        staging, quarantine=bad, structure_quarantine=structure_bad, criterion_unavailable={},
        missing_autoids=[], manifest_cases=None, expected_machine_sha256=mm_sha,
        previously_owned_autoids=[], resolved_governing_spec=spec_name,
        resolved_governing_spec_status=str(spec_status["status"]),
        mindmap_source_sha256=rstate["source_sha256"],
        resolved_defect_spec_status=str(defect["status"]),
        resolved_defect_spec_receipt_sha256=str(defect.get("receipt_sha256") or "") or None,
        resolved_defect_spec_receipt=defect_receipt, mindmap_text=text, spec_text=spec_text,
        criterion_version_family=family, criterion_manual_version=manual,
        criterion_rule_records=rule_records or None)
    return {"summary": summary, "staging": staging, "machine_mindmap": mm_data,
            "machine_mindmap_sha256": mm_sha, "structure_quarantine": structure_bad,
            "verbatim_quarantine": bad}


def _publish(batch: Path, staging: Path) -> None:
    """nodes.py `_publish_staged_projection`：contracts/ 与披露旁车整体换进批目录。"""
    from cex_core.engine.case_compiler.mindmap_contract_projector import (
        MACHINE_MINDMAP_DISCLOSURES_SIDECAR_NAME as SIDECAR,
    )

    token = uuid.uuid4().hex
    moved: list[tuple[Path, Path]] = []
    try:
        for name in ("contracts", SIDECAR):
            current = batch / name
            if current.is_symlink():
                raise ClientError(f"{current} is a symlink; refusing to publish over it")
            if current.exists():
                backup = batch / f".{name}.author-backup-{token}"
                os.rename(current, backup)
                moved.append((backup, current))
        for name in ("contracts", SIDECAR):
            if (staging / name).exists():
                os.rename(staging / name, batch / name)
    except BaseException:
        for backup, current in moved:
            if current.exists():
                shutil.rmtree(current) if current.is_dir() else current.unlink()
            os.rename(backup, current)
        raise
    for backup, _current in moved:
        shutil.rmtree(backup) if backup.is_dir() else backup.unlink()


def _receipt(batch: Path, projected: dict[str, Any], rstate: dict[str, Any]) -> dict[str, Any]:
    """nodes.py 在投影发布后记下的 recompose_done 事实（后续一致性要求、出处核对都认它）。"""
    summary = projected["summary"]
    spec_status, spec_raw = _status(batch, "governing_spec_status.json")
    defect, defect_raw = _status(batch, "defect_spec_status.json")
    return {
        "ev": "recompose_done", "reentry_round": 0,
        "written": len(summary["written"]), "abandoned": len(summary["abandoned"]),
        "needs_decision": len(summary["needs_decision"]),
        "disclosures": len(summary["disclosures"]), "quarantined": len(summary["quarantined"]),
        "bucket_counts": summary["bucket_counts"],
        "source_status_counts": summary["source_status_counts"],
        "typed_pending_autoids": list(summary["typed_pending"]),
        "typed_ready_autoids": list(summary["typed_ready"]),
        "provisional_spec_unknown_autoids": list(summary["provisional_spec_unknown_autoids"]),
        "governing_spec": spec_status.get("name") if spec_status.get("status") == "bound" else None,
        "governing_spec_status": spec_status["status"],
        "governing_spec_sha256": spec_status.get("sha256"),
        "governing_spec_size": spec_status.get("size"),
        "governing_spec_generation_id": spec_status.get("generation_id"),
        "governing_spec_manifest_sha256": spec_status.get("manifest_sha256"),
        "governing_spec_status_sha256": _sha256_bytes(spec_raw),
        "defect_spec_status": defect["status"],
        "defect_spec_receipt_sha256": defect.get("receipt_sha256"),
        "defect_spec_status_sha256": _sha256_bytes(defect_raw),
        "mindmap_source_sha256": rstate["source_sha256"],
        "machine_mindmap_sha256": projected["machine_mindmap_sha256"],
        "written_autoids": list(summary["written"]),
        "abandoned_autoids": list(summary["abandoned"]),
        "contract_sha256_by_autoid": dict(summary["contract_sha256_by_autoid"]),
        "disclosure_sha256": summary["disclosure_sha256"],
        "projection_sha256": summary["disclosure_sha256"],
    }


def _stamp_intent(ws: Workspace, root: Path, batch: Path, aid: str, receipt: dict[str, Any],
                  case: dict[str, Any] | None) -> dict[str, Any]:
    """nodes.py `_stamp_intent`：每案 intent.json（author_claims 是断言兑现 Author 期望的出处）。"""
    from cex_core.engine.case_compiler._sealed_io import read_regular_nofollow
    from cex_core.engine.case_compiler.contract_entry import (
        normalize_contract,
        write_intent_json_atomic,
        write_json_atomic,
    )
    from cex_core.engine.case_compiler.domain_grammar import forbidden_mechanism_intents
    from cex_core.engine.ist_core.compile_engine.consistency_requirement import (
        resolve_consistency_requirement,
    )

    case_dir = ws.outputs_dir / aid
    marker = case_dir / "intent_stamp_status.json"
    case_dir.mkdir(parents=True, exist_ok=True)
    write_json_atomic(marker, {"schema": _INTENT_STAMP_SCHEMA, "autoid": aid, "status": "pending"})
    if not isinstance(case, dict):
        raise ClientError(f"case {aid} is missing from the mindmap")
    payload: dict[str, Any] = {
        "autoid": aid, "title": str(case.get("title") or ""),
        "step_intents": case.get("step_intents") or [], "group_path": case.get("group_path") or [],
        "source": "manifest", "stamped_by": "engine.author",
        "consistency_requirement": "required", "consistency_binding_status": "pending",
        "consistency_contract_path": None, "consistency_contract_sha256": None,
        "consistency_receipt_sha256": None,
        "governing_spec_status": str(receipt.get("governing_spec_status") or "unknown"),
    }
    if receipt.get("governing_spec_status") == "bound":
        payload["governing_spec"] = receipt.get("governing_spec")
        payload["governing_spec_identity"] = {
            key: receipt.get(f"governing_spec_{field}") for key, field in (
                ("name", "name"), ("sha256", "sha256"), ("size", "size"),
                ("generation_id", "generation_id"), ("manifest_sha256", "manifest_sha256"))}
        payload["governing_spec_identity"]["name"] = receipt.get("governing_spec")
    contract_path = batch / "contracts" / f"{aid}.json"
    expected = str((receipt.get("contract_sha256_by_autoid") or {}).get(aid) or "")
    raw = read_regular_nofollow(
        contract_path, trusted_root=ws.outputs_dir, error_type=ClientError,
        invalid_message="machine contract path is invalid",
        directory_message="machine contract directory is unavailable",
        open_message="machine contract is unavailable",
        bounds_message="machine contract exceeds its sealed size boundary",
        changed_message="machine contract changed while being read",
        max_bytes=16 * 1024 * 1024, min_bytes=1)
    if _sha256_bytes(raw) != expected:
        raise ClientError(f"typed expectation contract identity drift for {aid}")
    contract = json.loads(raw.decode("utf-8"))
    payload["typed_expectation_contract_sha256"] = expected
    payload["typed_expectation_contract_path"] = contract_path.relative_to(ws.root).as_posix()
    status = str(contract.get("typed_assertion_status") or "ready")
    if status not in ("ready", "pending"):
        raise ClientError("typed expectation contract status is invalid")
    payload["typed_expectation_status"] = status
    typed, claims, defect_claims = {}, {}, {}
    for item in normalize_contract(contract, contract_path.name).get("expectations") or []:
        assertion = item.get("assertion") if isinstance(item, dict) else None
        claim = item.get("author_claim") if isinstance(item, dict) else None
        defect_claim = item.get("defect_spec_claim") if isinstance(item, dict) else None
        if isinstance(assertion, dict):
            typed[str(assertion.get("expectation_id") or "")] = assertion
        elif isinstance(claim, dict):
            claims[str(claim.get("expectation_id") or "")] = claim
        elif isinstance(defect_claim, dict):
            defect_claims[str(defect_claim.get("expectation_id") or "")] = defect_claim
        else:
            raise ClientError("typed expectation entry is absent")
    payload.update({"typed_expectations": typed, "author_claims": claims,
                    "defect_spec_claims": defect_claims})
    proof = resolve_consistency_requirement(outputs_root=ws.outputs_dir, project_root=root,
                                            batch_name=batch.name, autoid=aid, facts=[receipt])
    payload["governing_spec_status"] = proof["governing_spec_status"]
    payload["consistency_requirement"] = proof["requirement"]
    payload["consistency_binding_status"] = proof["binding_status"]
    haystack = " ".join([payload["title"]] + [
        f"{si.get('desc') or ''} {si.get('expected') or ''}"
        for si in payload["step_intents"] if isinstance(si, dict)]).lower()
    hits = [{"family": family, "matched": pattern}
            for family, patterns in forbidden_mechanism_intents()
            for pattern in patterns if re.search(pattern, haystack)]
    if hits:
        payload["forbidden_mechanism"] = hits[:3]
    write_intent_json_atomic(case_dir / "intent.json", payload)
    write_json_atomic(marker, {"schema": _INTENT_STAMP_SCHEMA, "autoid": aid, "status": "complete"})
    return proof


