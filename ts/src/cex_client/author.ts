export async function criterionRecord(ws: Workspace, outName: string, shapeKey: string, judgment: unknown): Promise<Record<string, unknown>> {
  const state = _loadState(ws, outName);
  await _requireCurrentSeal(ws, state);
  const [, info] = engineEnvPrepare(ws, { pinned: state.data_root });
  const brief = ((state.pending as Record<string, unknown>)?.[String(shapeKey ?? "")] ?? null) as Record<string, any> | null;
  if (brief === null) {
    throw new ClientError(`shape ${JSON.stringify(shapeKey)} is not pending; pending: ${JSON.stringify(Object.keys(state.pending ?? {}).sort())}`);
  }
  const { CriterionAuthorRuleError, parse_engine_adjudication_result, persist_engine_adjudications } = await import("../cex_core/engine/case_compiler/criterion_author_rules.js");
  const reply = typeof judgment === "string" ? judgment : JSON.stringify(judgment);
  let decisions: unknown;
  try {
    decisions = parse_engine_adjudication_result(reply, { brief: brief as Record<string, any> });
  } catch (exc: unknown) {
    if (exc instanceof CriterionAuthorRuleError) {
      return {
        ok: false,
        status: "rejected",
        error: (exc as Error).message,
        legal_form: "One JSON object with criterion_type (copied from the brief's catalogue), rationale (English) and disclosure (Chinese); optionally manual_anchor_ids / tree_context_ids / behaviour_classes. No other keys.",
      };
    }
    throw exc;
  }
  const [, , manual] = await _versions(info);
  const records = persist_engine_adjudications(decisions as Record<string, any>[], { brief: state.brief as Record<string, any>, manual_version: manual || null });
  const local = localRulesPath(ws);
  fs.mkdirSync(path.dirname(local), { recursive: true });
  const lock = stateLock(ws, "criterion-rules");
  try {
    const known = new Set<string>();
    if (fs.existsSync(local)) {
      for (const line of fs.readFileSync(local, "utf8").split("\n").filter(Boolean)) {
        try { known.add(String(JSON.parse(line).rule_sha256)); } catch {}
      }
    }
    const append: string[] = [];
    for (const record of records) {
      if (!known.has(String(record.rule_sha256))) {
        append.push(JSON.stringify(record, Object.keys(record).sort()) + "\n");
      }
    }
    if (append.length) fs.appendFileSync(local, append.join(""), "utf8");
  } finally {
    lock.release();
  }
  const recordShape = (current: Record<string, unknown>) => {
    current.round_records = [...((current.round_records as unknown[]) ?? []), ...records];
    current.pending = Object.fromEntries(Object.entries((current.pending as Record<string, unknown>) ?? {}).filter(([k]) => k !== shapeKey));
  };
  const newState = _updateState(ws, outName, recordShape);
  const decided = records.map((r: Record<string, unknown>) => ({
    rule_id: r.rule_id,
    criterion_type: (r.output as Record<string, unknown>)?.criterion_type,
    disclosure: r.disclosure,
  }));
  if (Object.keys(newState.pending ?? {}).length) {
    return { ok: true, status: "recorded", decided, pending_shapes: _pendingView(ws, newState) };
  }
  return { status: "recorded", decided, ...(await _projectAndPublish(ws, newState)) };
}

