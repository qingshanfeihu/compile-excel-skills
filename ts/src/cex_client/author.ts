async function _project(root: string, batch: string, rstate: Record<string, unknown>, info: Record<string, unknown>, ruleRecords?: Record<string, unknown> | null): Promise<Record<string, unknown>> {
  const { fill_mechanical_fields, load_machine_mindmap, project_machine_mindmap, verbatim_failures } = await import("../cex_core/engine/case_compiler/mindmap_contract_projector.js");
  const { object_kind_closed_set, sealed_structure_failures, strip_engine_slots } = await import("../cex_core/engine/case_compiler/step_structure.js");

  const [specStatus] = _status(batch, "governing_spec_status.json");
  const [defect] = _status(batch, "defect_spec_status.json");
  const sourceRaw = fs.readFileSync(path.join(batch, "mindmap_source.json"));
  const text = sourceRaw.toString("utf8").replace(new RegExp(`^[${_STRIP}]+`), "");
  const specText = _specText(root, specStatus);
  const specName = (specStatus.status === "bound" ? specStatus.name : null) as string | null;
  const defectReceipt = typeof defect.receipt === "object" && defect.receipt !== null ? defect.receipt as Record<string, unknown> : null;
  const mmPath = path.join(batch, "machine_mindmap.json");
  const [mmData, mmSha] = load_machine_mindmap(mmPath);
  fill_mechanical_fields(mmData, text);
  const kinds = object_kind_closed_set();
  const structureBad: Record<string, string[]> = {};
  for (const case_ of (mmData.cases as unknown[]) ?? []) {
    if (typeof case_ !== "object" || case_ === null) continue;
    strip_engine_slots(case_);
    const codes = sealed_structure_failures(case_, { object_kinds: kinds });
    if (codes.length) structureBad[String((case_ as Record<string, unknown>).autoid ?? "")] = codes;
  }
  const bad = verbatim_failures(mmData, text, specText, {
    governing_spec: specName,
    governing_spec_status: String(specStatus.status),
    defect_spec_receipt: defectReceipt,
    defect_spec_status: String(defect.status),
    defect_spec_receipt_sha256: String(defect.receipt_sha256 ?? "") || null,
  });
  const [, family, manual] = await _versions(info);
  const staging = path.join(batch, `.author-projection-${crypto.randomUUID().replace(/-/g, "")}`);
  fs.mkdirSync(staging);
  fs.copyFileSync(mmPath, path.join(staging, "machine_mindmap.json"));
  const summary = project_machine_mindmap(staging, {
    quarantine: bad,
    structure_quarantine: structureBad,
    criterion_unavailable: {},
    missing_autoids: [],
    manifest_cases: null,
    expected_machine_sha256: mmSha,
    previously_owned_autoids: [],
    resolved_governing_spec: specName as string | null,
    resolved_governing_spec_status: String(specStatus.status),
    mindmap_source_sha256: rstate.source_sha256 as string,
    resolved_defect_spec_status: String(defect.status),
    resolved_defect_spec_receipt_sha256: String(defect.receipt_sha256 ?? "") || null,
    resolved_defect_spec_receipt: defectReceipt,
    mindmap_text: text,
    spec_text: specText,
    criterion_version_family: family,
    criterion_manual_version: manual,
    criterion_rule_records: ruleRecords ?? null,
  });
  return { summary, staging, machine_mindmap: mmData, machine_mindmap_sha256: mmSha, structure_quarantine: structureBad, verbatim_quarantine: bad };
}

function _publish(batch: string, staging: string): void {
  const { MACHINE_MINDMAP_DISCLOSURES_SIDECAR_NAME: SIDECAR } = require("../cex_core/engine/case_compiler/mindmap_contract_projector.js");
  const token = crypto.randomUUID().replace(/-/g, "");
  const moved: [string, string][] = [];
  try {
    for (const name of ["contracts", SIDECAR]) {
      const current = path.join(batch, name);
      if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) {
        throw new ClientError(`${current} is a symlink; refusing to publish over it`);
      }
      if (fs.existsSync(current)) {
        const backup = path.join(batch, `.${name}.author-backup-${token}`);
        fs.renameSync(current, backup);
        moved.push([backup, current]);
      }
    }
    for (const name of ["contracts", SIDECAR]) {
      const src = path.join(staging, name);
      if (fs.existsSync(src)) {
        fs.renameSync(src, path.join(batch, name));
      }
    }
  } catch (e) {
    for (const [backup, current] of moved) {
      if (fs.existsSync(current)) fs.rmSync(current, { recursive: true, force: true });
      fs.renameSync(backup, current);
    }
    throw e;
  }
  for (const [backup] of moved) {
    fs.rmSync(backup, { recursive: true, force: true });
  }
}

