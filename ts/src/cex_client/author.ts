async function _allowedSlots(): Promise<Record<string, string[][]>> {
  const { CRITERION_TYPE_ALLOWED_SLOTS } = await import("../cex_core/engine/case_compiler/criterion_carriers.js");
  const out: Record<string, string[][]> = {};
  for (const [ctype, pairs] of Object.entries(CRITERION_TYPE_ALLOWED_SLOTS)) {
    out[ctype] = [...pairs].sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1])).map(([k, op]) => [String(k), String(op)]);
  }
  return out;
}

function _cardView(batch: string, aid: string, slots: Record<string, string[][]>, mmCase: Record<string, unknown> | undefined): Record<string, unknown> {
  const contract = JSON.parse(fs.readFileSync(path.join(batch, "contracts", `${aid}.json`), "utf8"));
  const expectations = [];
  for (const item of (contract.expectations as unknown[]) ?? []) {
    if (typeof item !== "object" || item === null) continue;
    const i = item as Record<string, unknown>;
    const claim = (i.author_claim ?? i.defect_spec_claim ?? {}) as Record<string, unknown>;
    const normalized = (i.normalized_claim ?? {}) as Record<string, unknown>;
    const ctype = String(normalized.criterion_type ?? "");
    expectations.push({
      expectation_id: claim.expectation_id,
      semantic_key: claim.semantic_key,
      text: i.text,
      claim_kind: claim.kind,
      criterion_type: ctype || null,
      criterion_label: normalized.criterion_label_zh,
      allowed_slots: JSON.parse(JSON.stringify(slots[ctype] ?? [])),
      authored_step: normalized.authored_step,
      fixture_mode: normalized.mode,
    });
  }
  return {
    autoid: aid,
    title: contract.intent_verbatim,
    group_path: (contract.mindmap_group as Record<string, unknown> | undefined)?.group_path,
    bucket: contract.bucket,
    author_steps: contract.author_steps,
    adapted_steps: contract.adapted_steps,
    step_structure: contract.step_structure,
    concretizations: JSON.parse(JSON.stringify(mmCase?.concretizations ?? [])),
    consistency: contract.consistency,
    device_disclosure: contract.device_disclosure,
    expectations,
    contract_path: path.join(batch, "contracts", `${aid}.json`),
  };
}

export function clientDisclosureMessage(message: string): string {
  let text = String(message ?? "").replace(_VETO_INVITATION, _VETO_NOTE);
  if (text.includes("否决并重裁")) {
    text = text.split("；").map((part) => part.includes("否决并重裁") ? _VETO_NOTE : part).join("；");
  }
  return text;
}

function _pendingView(ws: Workspace, state: Record<string, unknown>): Record<string, unknown>[] {
  const out = [];
  for (const [key, brief] of Object.entries((state.pending as Record<string, Record<string, unknown>>) ?? {}).sort()) {
    const shape = ((brief as Record<string, unknown>).shapes as Record<string, unknown>[])[0] ?? {};
    out.push({
      shape_key: key,
      members: shape.members,
      claims: ((shape.claims as Record<string, unknown>[]) ?? []).map((c: Record<string, unknown>) => ({
        autoid: c.autoid,
        expectation_id: c.expectation_id,
        original_text: c.original_text,
      })),
      criterion_types: ((brief.criterion_types as Record<string, unknown>[]) ?? []).map((row: Record<string, unknown>) => row.criterion_type),
      brief_path: fromStatePath(ws, String((state.brief_paths as Record<string, unknown>)[key])),
    });
  }
  return out;
}

