const _CASES_SCHEMA_NOTE = "generated by cex_author_emit from sealed mechanical cases";

function _statePath(ws: Workspace, outName: string): string {
  return path.join(ws.stateDir, "author", `${safeComponent(outName, "batch name")}.json`);
}

function _loadState(ws: Workspace, outName: string): Record<string, unknown> {
  const state = readPrivateJson(_statePath(ws, outName));
  if (!state || state.schema !== STATE_SCHEMA) {
    throw new ClientError(`no authoring dispatch for ${JSON.stringify(outName)}; call cex_author_prepare`);
  }
  return state;
}

function _saveState(ws: Workspace, state: Record<string, unknown>): void {
  writePrivateJson(_statePath(ws, String(state.out_name)), { ...state, schema: STATE_SCHEMA });
}

function _updateState(ws: Workspace, outName: string, change: (state: Record<string, unknown>) => void): Record<string, unknown> {
  const lock = stateLock(ws, "author", outName);
  try {
    const state = readPrivateJson(_statePath(ws, outName)) ?? {};
    state.out_name = state.out_name ?? outName;
    change(state);
    _saveState(ws, state);
    return state;
  } finally {
    lock.release();
  }
}

export function casesRoot(ws: Workspace, outName: string): string {
  return path.join(ws.outputsDir, safeComponent(outName, "batch name"), "cases");
}

function _sha256Bytes(raw: Buffer): string {
  return crypto.createHash("sha256").update(raw).digest("hex");
}

function _canonicalSha256(value: unknown): string {
  return _sha256Bytes(Buffer.from(canonicalJson(value), "utf8"));
}

async function _sealedBatch(ws: Workspace, outName: string): Promise<[Record<string, unknown>, string]> {
  const { _loadState: loadRecomposeState } = await import("./recompose.js");
  const rstate = loadRecomposeState(ws, outName);
  const { verify_machine_mindmap_submission_commit } = await import("../cex_core/engine/ist_core/tools/device/recompose_submission.js");
  try {
    verify_machine_mindmap_submission_commit(ws.outputsDir, String(rstate.out_name), String(rstate.dispatch_id), { expected_binding: rstate.binding as Record<string, any> | null | undefined });
  } catch (exc) {
    throw new ClientError(`the machine mindmap of ${JSON.stringify(outName)} is not sealed (${exc instanceof Error ? exc.constructor.name : "Error"}: ${exc}); call cex_recompose_seal first`);
  }
  return [rstate, path.join(ws.outputsDir, String(rstate.out_name))];
}

async function _currentSealSha(ws: Workspace, outName: string, pinned?: unknown): Promise<string> {
  engineEnvPrepare(ws, { pinned });
  const [, batch] = await _sealedBatch(ws, outName);
  const { load_machine_mindmap } = await import("../cex_core/engine/case_compiler/mindmap_contract_projector.js");
  const [, sha] = load_machine_mindmap(path.join(batch, "machine_mindmap.json"));
  return sha;
}

async function _requireCurrentSeal(ws: Workspace, state: Record<string, unknown>): Promise<void> {
  const outName = String(state.out_name);
  let current: string;
  try {
    current = await _currentSealSha(ws, outName, state.data_root);
  } catch (exc) {
    if (exc instanceof ClientError) {
      throw new ClientError(
        `authoring ${JSON.stringify(outName)} needs its recompose batch sealed, and it is not: ${exc}. cex_recompose_prepare reopens a sealed batch and removes machine_mindmap.json; call cex_recompose_seal, then cex_author_prepare, then continue`);
    }
    throw exc;
  }
  const expected = String(state.projected_machine_mindmap_sha256 ?? (state.receipt as Record<string, unknown> | undefined)?.machine_mindmap_sha256 ?? "");
  if (!expected) {
    throw new ClientError(`the authoring state of ${JSON.stringify(outName)} does not say which sealed machine mindmap it was projected from; call cex_author_prepare again`);
  }
  if (current !== expected) {
    throw new ClientError(
      `the recompose batch ${JSON.stringify(outName)} was sealed again since cex_author_prepare (the contract cards come from machine mindmap ${expected.slice(0, 12)}, the seal is now ${current.slice(0, 12)}); call cex_author_prepare to re-project the contract cards, then continue`);
  }
}

function _status(batch: string, name: string): [Record<string, unknown>, Buffer] {
  const raw = fs.readFileSync(path.join(batch, name));
  return [JSON.parse(raw.toString("utf8")), raw];
}

function _specText(root: string, specStatus: Record<string, unknown>): string | null {
  if (specStatus.status !== "bound") return null;
  const p = path.join(root, "knowledge", "data", "spec", "generations",
    safeComponent(specStatus.generation_id, "spec generation"), "docs",
    safeComponent(specStatus.name, "spec name"));
  const raw = fs.readFileSync(p);
  if (_sha256Bytes(raw) !== specStatus.sha256) {
    throw new ClientError("the bound governing spec changed after recompose; call cex_recompose_prepare again");
  }
  return raw.toString("utf8");
}

async function _manifestCases(text: string): Promise<Record<string, Record<string, unknown>>> {
  const { _extract_cases } = await import("../cex_core/engine/ist_core/tools/device/compile_prep.js");
  const roots = JSON.parse(text);
  const cases: Record<string, Record<string, unknown>> = {};
  for (const root of Array.isArray(roots) ? roots : [roots]) {
    if (typeof root !== "object" || root === null) continue;
    for (const case_ of _extract_cases(root)) {
      cases[String(case_.autoid)] = case_;
    }
  }
  return cases;
}

