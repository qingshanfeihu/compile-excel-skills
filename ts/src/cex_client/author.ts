async function _stampIntent(ws: Workspace, root: string, batch: string, caseRoot: string, aid: string, receipt: Record<string, unknown>, case_: Record<string, unknown> | undefined): Promise<Record<string, unknown>> {
  const { read_regular_nofollow } = await import("../cex_core/engine/case_compiler/_sealed_io.js");
  const { normalize_contract, write_intent_json_atomic, write_json_atomic } = await import("../cex_core/engine/case_compiler/contract_entry.js");
  const { forbidden_mechanism_intents } = await import("../cex_core/engine/case_compiler/domain_grammar.js");
  const { resolve_consistency_requirement } = await import("../cex_core/engine/ist_core/compile_engine/consistency_requirement.js");

  const caseDir = path.join(caseRoot, safeComponent(aid, "autoid"));
  const marker = path.join(caseDir, "intent_stamp_status.json");
  fs.mkdirSync(caseDir, { recursive: true });
  write_json_atomic(marker, { schema: _INTENT_STAMP_SCHEMA, autoid: aid, status: "pending" });
  if (typeof case_ !== "object" || case_ === null) {
    throw new ClientError(`case ${aid} is missing from the mindmap`);
  }
  const payload: Record<string, unknown> = {
    autoid: aid,
    title: String(case_.title ?? ""),
    step_intents: case_.step_intents ?? [],
    group_path: case_.group_path ?? [],
    source: "manifest",
    stamped_by: "engine.author",
    consistency_requirement: "required",
    consistency_binding_status: "pending",
    consistency_contract_path: null,
    consistency_contract_sha256: null,
    consistency_receipt_sha256: null,
    governing_spec_status: String(receipt.governing_spec_status ?? "unknown"),
  };
  if (receipt.governing_spec_status === "bound") {
    payload.governing_spec = receipt.governing_spec;
    payload.governing_spec_identity = {
      name: receipt.governing_spec,
      sha256: receipt.governing_spec_sha256,
      size: receipt.governing_spec_size,
      generation_id: receipt.governing_spec_generation_id,
      manifest_sha256: receipt.governing_spec_manifest_sha256,
    };
  }
  const contractPath = path.join(batch, "contracts", `${aid}.json`);
  const expected = String((receipt.contract_sha256_by_autoid as Record<string, unknown> | undefined)?.[aid] ?? "");
  const raw = read_regular_nofollow(contractPath, {
    trusted_root: ws.outputsDir,
    errorType: ClientError,
    invalid_message: "machine contract path is invalid",
    directory_message: "machine contract directory is unavailable",
    open_message: "machine contract is unavailable",
    bounds_message: "machine contract exceeds its sealed size boundary",
    changed_message: "machine contract changed while being read",
    max_bytes: 16 * 1024 * 1024,
    min_bytes: 1,
  }) as Buffer;
  if (_sha256Bytes(raw) !== expected) {
    throw new ClientError(`typed expectation contract identity drift for ${aid}`);
  }
  const contract = JSON.parse(raw.toString("utf8"));
  payload.typed_expectation_contract_sha256 = expected;
  payload.typed_expectation_contract_path = path.relative(ws.root, contractPath).split(path.sep).join("/");
  const status = String(contract.typed_assertion_status ?? "ready");
  if (!["ready", "pending"].includes(status)) {
    throw new ClientError("typed expectation contract status is invalid");
  }
  payload.typed_expectation_status = status;
  const typed: Record<string, unknown> = {};
  const claims: Record<string, unknown> = {};
  const defectClaims: Record<string, unknown> = {};
  for (const item of (normalize_contract(contract, path.basename(contractPath)).expectations as unknown[]) ?? []) {
    if (typeof item !== "object" || item === null) continue;
    const i = item as Record<string, unknown>;
    const assertion = i.assertion;
    const claim = i.author_claim;
    const defectClaim = i.defect_spec_claim;
    if (typeof assertion === "object" && assertion !== null) {
      typed[String((assertion as Record<string, unknown>).expectation_id ?? "")] = assertion;
    } else if (typeof claim === "object" && claim !== null) {
      claims[String((claim as Record<string, unknown>).expectation_id ?? "")] = claim;
    } else if (typeof defectClaim === "object" && defectClaim !== null) {
      defectClaims[String((defectClaim as Record<string, unknown>).expectation_id ?? "")] = defectClaim;
    } else {
      throw new ClientError("typed expectation entry is absent");
    }
  }
  payload.typed_expectations = typed;
  payload.author_claims = claims;
  payload.defect_spec_claims = defectClaims;
  const proof = resolve_consistency_requirement({ outputs_root: ws.outputsDir, project_root: root, batch_name: path.basename(batch), autoid: aid, facts: [receipt] });
  payload.governing_spec_status = proof.governing_spec_status;
  payload.consistency_requirement = proof.requirement;
  payload.consistency_binding_status = proof.binding_status;
  const haystack = [payload.title, ...((payload.step_intents as Record<string, unknown>[]) ?? []).map((si) => `${si.desc ?? ""} ${si.expected ?? ""}`)].join(" ").toLowerCase();
  const hits = [];
  for (const [family, patterns] of forbidden_mechanism_intents()) {
    for (const pattern of patterns) {
      if (new RegExp(pattern).test(haystack)) hits.push({ family, matched: pattern });
    }
  }
  if (hits.length) payload.forbidden_mechanism = hits.slice(0, 3);
  write_intent_json_atomic(path.join(caseDir, "intent.json"), payload);
  write_json_atomic(marker, { schema: _INTENT_STAMP_SCHEMA, autoid: aid, status: "complete" });
  return proof;
}

